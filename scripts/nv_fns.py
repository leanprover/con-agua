#!/usr/bin/env python3
"""Regenerate `nvFns` in ConAgua/Checker/NoVerdictFns.lean: the functions of `checkerProg` whose call
closure aborts only with class-0 codes (`ConAgua/Checker/NoVerdictClosed.lean` fails when it is stale).
Needs ConAgua.Checker.Prog built. Usage: scripts/nv_fns.py [--check]"""
import os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = subprocess.run([os.path.join(ROOT, "scripts", "lake"), "env", "lean", "scripts/nv_fns.lean"],
                     cwd=ROOT, capture_output=True, text=True)
fns = [l[3:].strip() for l in out.stdout.splitlines() if l.startswith("FN ")]
if not fns:
    sys.exit("no output:\n" + out.stdout + out.stderr)
lines, cur = [], "  ["
for f in fns:
    t = '"%s", ' % f
    if len(cur) + len(t) > 100:
        lines.append(cur.rstrip()); cur = "   "
    cur += t
lines.append(cur.rstrip().rstrip(",") + "]")
p = os.path.join(ROOT, "ConAgua", "Checker", "NoVerdictFns.lean")
new = f'''import ConAgua.L.Syntax

/-!
# The functions that claim no verdict (generated by `scripts/nv_fns.py`; do not edit)

The functions of `checkerProg` whose call closure aborts only with constant class-`0` codes
({len(fns)} names). `Checker/NoVerdictClosed.lean` checks it (`closedNV`).
-/

namespace L.Checker

/-- The functions outside the verdict closure. -/
def nvFns : List L.FnName :=
''' + "\n".join(lines) + "\n\nend L.Checker\n"
old = open(p).read() if os.path.exists(p) else ""
if "--check" in sys.argv:
    sys.exit(0 if new == old else "nvFns is stale: run scripts/nv_fns.py")
open(p, "w").write(new)
print(len(fns), "functions")
