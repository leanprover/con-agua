#!/usr/bin/env python3
"""The reason table: the codes of `abort R` / `fail R` and the harness's messages.

An abort's code (`L.Err.abort k`, the compiled program's `rax` on its `ca_abort` exit) is
`k = 4 * r + c`: `c` the class (`0` other, `1` reject, `2` decline), `r` the reason, a row of
`scripts/reasons.tsv` (numbered from 1 in file order; `0` is no reason). The rows are the twin's own
messages (every distinct string literal of a `.invalid`, `.notImplemented` or frontend `.declined`
error in `vendor/con-ron/ConRon/Arena`, interpolations shown as `…`: class 1 for `invalid`, 2 for the
others) and, at the end, L's own reasons (class 0: capacities, defensive checks).

Usage:
  scripts/reasons.py           regenerate ConAgua/Arena/Reasons.lean and reasons.h from the table
  scripts/reasons.py --check   fail if they are stale, or if a twin message has no row (a gate, no build)
  scripts/reasons.py --add     append a row for every twin message without one (after a twin bump)
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "scripts", "reasons.tsv")
LEAN = os.path.join(ROOT, "ConAgua", "Arena", "Reasons.lean")
HDR = os.path.join(ROOT, "reasons.h")
CLASS = {"other": 0, "reject": 1, "decline": 2}


def strings(seg):
    """The string literals of `seg` (not those inside an interpolation), interpolations as `…`,
    whitespace collapsed."""
    out, i = [], 0
    while i < len(seg):
        interp = seg.startswith('s!"', i)
        if not interp and seg[i] != '"':
            i += 1
            continue
        i += 3 if interp else 1
        t, depth = [], 0
        while i < len(seg):
            c = seg[i]
            if depth == 0 and c == "\\":
                t.append(seg[i:i + 2])
                i += 2
                continue
            if depth == 0 and c == '"':
                break
            if interp and c == "{":
                if depth == 0:
                    t.append("…")
                depth += 1
            elif interp and c == "}":
                depth -= 1
            elif depth == 0:
                t.append(c)
            i += 1
        i += 1
        t = re.sub(r"\s+", " ", "".join(t).replace('\\"', '"').replace("\\n", " ")).strip()
        if t.strip("… ;:"):
            out.append(t)
    return out


def balanced(s, i):
    d = 0
    for j in range(i, len(s)):
        if s[j] == "(":
            d += 1
        elif s[j] == ")":
            d -= 1
            if d == 0:
                return s[i:j + 1]
    return s[i:]


def twin_messages():
    """(class, message) for every distinct reject/decline literal of the twin's arena."""
    seen = {}
    files = sorted(glob.glob(os.path.join(ROOT, "vendor", "con-ron", "ConRon", "Arena", "**", "*.lean"),
                             recursive=True))
    for f in files:
        if f.endswith("Test.lean"):
            continue
        s = re.sub(r"\\\n\s*", "", open(f, encoding="utf-8").read())  # Lean's string gaps
        for m in re.finditer(r"\.(invalid|notImplemented|declined)\s*(?=\(|s!\"|\")", s):
            rest = s[m.end():]
            seg = balanced(rest, 0) if rest.startswith("(") else rest.split("\n")[0]
            cls = "reject" if m.group(1) == "invalid" else "decline"
            for t in strings(seg):
                if t.startswith("…"):  # a wrapper around another message (`{w} (line {n})`)
                    continue
                seen.setdefault((cls, t), os.path.relpath(f, ROOT))
    # con-leche's message for a nonstandard axiom (the twin calls `ConLeche.nonStdAxiomMsg`)
    for f in glob.glob(os.path.join(ROOT, "vendor", "con-leche", "ConLeche", "**", "*.lean"), recursive=True):
        s = re.sub(r"\\\n\s*", "", open(f, encoding="utf-8").read())
        m = re.search(r"def nonStdAxiomMsg[^\n]*\n((?:  [^\n]*\n)+)", s)
        if m:
            for t in strings(m.group(1)):
                seen.setdefault(("decline", t), os.path.relpath(f, ROOT))
    return seen


def read_table():
    rows = []
    for line in open(TSV, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        name, cls, msg = line.rstrip("\n").split("\t")
        rows.append((name, cls, msg))
    return rows


def lean_text(rows):
    out = ["module", "", "public import ConAgua.L.Syntax", "", "@[expose] public section", "", "/-!",
           "# Abort reasons (generated by `scripts/reasons.py` from `scripts/reasons.tsv`; do not edit)", "",
           "An abort's code is `4 * r + c`: `c` the class (`0` other, `1` reject, `2` decline), `r` the",
           "reason, whose message the harness prints (`reasons.h`). `fail R` aborts with `R` (class 0 inside a",
           "pin-variant attempt, `L.Arena.ATT`), `abort R` with `R` as it is.", "-/", "", "namespace L.Arena", ""]
    for i, (name, cls, msg) in enumerate(rows, 1):
        out.append(f"/-- {cls}: {msg.replace('-/', '- /')} -/")
        out.append(f"abbrev {name} : L.Word := {4 * i + CLASS[cls]}")
    out += ["", "end L.Arena", ""]
    return "\n".join(out)


def c_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def header_text(rows):
    out = ["/* The abort reasons: reasons[r] is the message of reason r, the code's bits 2 and up",
           "   (generated by scripts/reasons.py from scripts/reasons.tsv; do not edit). */",
           "static const char *const reasons[] = {", '  "",']
    for name, cls, msg in rows:
        out.append(f'  "{c_escape(msg)}",')
    out += ["};", ""]
    return "\n".join(out)


def name_for(msg, taken):
    words = re.findall(r"[A-Za-z0-9]+", msg)
    for n in range(3, len(words) + 1):
        name = "R_" + "_".join(w.upper() for w in words[:n])
        if name not in taken:
            return name
    name, k = "R_" + "_".join(w.upper() for w in words), 2
    while f"{name}_{k}" in taken:
        k += 1
    return f"{name}_{k}"


def main():
    args = sys.argv[1:]
    twin = twin_messages()
    rows = read_table() if os.path.exists(TSV) else []
    have = {(c, m) for _, c, m in rows}
    missing = [k for k in sorted(twin) if k not in have]
    if "--add" in args:
        taken = {n for n, _, _ in rows}
        with open(TSV, "a", encoding="utf-8") as fh:
            for cls, msg in missing:
                name = name_for(msg, taken)
                taken.add(name)
                fh.write(f"{name}\t{cls}\t{msg}\n")
        print(f"added {len(missing)} rows")
        rows = read_table()
        missing = []
    names = [n for n, _, _ in rows]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit(f"duplicate names: {sorted(dup)}")
    want = {LEAN: lean_text(rows), HDR: header_text(rows)}
    if "--check" in args:
        bad = [p for p, t in want.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        for cls, msg in missing:
            print(f"twin message without a row: {cls}: {msg}  ({twin[(cls, msg)]})")
        for p in bad:
            print(f"stale: {os.path.relpath(p, ROOT)} (run scripts/reasons.py)")
        sys.exit(1 if bad or missing else 0)
    for p, t in want.items():
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(t)
    if missing:
        print(f"{len(missing)} twin messages without a row (scripts/reasons.py --add)")


if __name__ == "__main__":
    main()
